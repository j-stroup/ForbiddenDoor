$countText = if ($sorted.Count -eq 1) { '1 entry' } else { "$($sorted.Count) entries" }
$page = $page.Replace('{{ROWS}}', $rows.ToString()).Replace('{{COUNT}}', $countText)
[IO.File]::WriteAllText((Join-Path $Site 'log.html'), $page, $Utf8)

# --- The "last change" line on the front page --------------------------------
$indexPath = Join-Path $Site 'index.html'
$index = [IO.File]::ReadAllText($indexPath, $Utf8)
$pattern = '(?s)<!-- log:latest -->.*?<!-- /log:latest -->'
if ($index -notmatch $pattern) {
  Write-Warning 'index.html has no <!-- log:latest --> markers; front page left alone.'
}
else {
  if ($sorted.Count -gt 0) {
    $latest = $sorted[0]
    $day = $latest.When.ToString('MMM d', $Culture)
    $inner = "<p class=""latest""><a href=""log.html""><span class=""latest-label"">Last change &middot; $day</span> $(Encode-Html $latest.Text)</a></p>"
  }
  else {
    $inner = ''
  }
  $newIndex = [regex]::Replace($index, $pattern, { param($m) "<!-- log:latest -->$inner<!-- /log:latest -->" })
  if ($newIndex -ne $index) {
    [IO.File]::WriteAllText($indexPath, $newIndex, $Utf8)
  }
}

Write-Host "Wrote $countText to $Site\log.html"
