        radial-gradient(circle at 50% 0%, rgba(120, 32, 18, 0.12) 0%, rgba(6, 6, 7, 0.96) 55%),
        repeating-linear-gradient(to bottom, rgba(255, 255, 255, 0.015) 0px, rgba(255, 255, 255, 0.015) 1px, transparent 1px, transparent 3px);
