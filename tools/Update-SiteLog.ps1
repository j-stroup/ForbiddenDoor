<#
  Builds the public change log for va0x.com from this repository.

  Only commits that opt in appear. Add a line like this anywhere in the
  commit message (it is the public wording, separate from the subject):

      Log: Choose your calling: Fighter, Mage, or Rogue

  Entries from before the log existed live in site-log-history.txt, next
  to this script, one per line:  yyyy-MM-dd HH:mm  text

  The script writes log.html into the site folder and refreshes the
  "last change" line in index.html, between these two markers:

      <!-- log:latest -->  ...  <!-- /log:latest -->

  Usage:   powershell -File tools\Update-SiteLog.ps1 [-Site <folder>]
#>
param(
  [string]$Site = (Join-Path $PSScriptRoot '..\..\..\Websites\va0x')
)

$ErrorActionPreference = 'Stop'
$Repo = Split-Path $PSScriptRoot -Parent
$Site = [IO.Path]::GetFullPath($Site)
$Utf8 = New-Object System.Text.UTF8Encoding($false)
$Culture = [Globalization.CultureInfo]::InvariantCulture

if (-not (Test-Path (Join-Path $Site 'index.html'))) {
  throw "No index.html in $Site. Pass the site folder with -Site."
}

function Encode-Html([string]$s) { [System.Net.WebUtility]::HtmlEncode($s) }

$entries = New-Object System.Collections.Generic.List[object]

# --- Entries written by hand, from before the log existed -------------------
$historyFile = Join-Path $PSScriptRoot 'site-log-history.txt'
if (Test-Path $historyFile) {
  foreach ($line in [IO.File]::ReadAllLines($historyFile, $Utf8)) {
    $t = $line.Trim()
    if ($t -eq '' -or $t.StartsWith('#')) { continue }
    if ($t -match '^(\d{4}-\d{2}-\d{2} \d{2}:\d{2})\s+(.+)$') {
      $when = [datetime]::ParseExact($Matches[1], 'yyyy-MM-dd HH:mm', $Culture)
      $entries.Add([pscustomobject]@{ When = $when; Text = $Matches[2].Trim() })
    }
    else {
      Write-Warning "Skipping unreadable history line: $t"
    }
  }
}

# --- Entries from commits with a "Log:" line --------------------------------
$oldEncoding = [Console]::OutputEncoding
[Console]::OutputEncoding = $Utf8
try {
  $raw = (& git -C $Repo log '--format=%x1e%aI%x1f%B') -join "`n"
}
finally {
  [Console]::OutputEncoding = $oldEncoding
}
if ($LASTEXITCODE -ne 0) { throw 'git log failed.' }

foreach ($commit in $raw -split [char]0x1e) {
  if ($commit.Trim() -eq '') { continue }
  $parts = $commit -split [char]0x1f, 2
  if ($parts.Count -lt 2) { continue }
  $when = [DateTimeOffset]::Parse($parts[0].Trim(), $Culture).LocalDateTime
  foreach ($line in $parts[1] -split "`n") {
    if ($line -match '^\s*Log:\s*(.+?)\s*$') {
      $entries.Add([pscustomobject]@{ When = $when; Text = $Matches[1] })
    }
  }
}

# Newest first, no duplicates
$seen = @{}
$sorted = $entries | Sort-Object When -Descending | Where-Object {
  $key = $_.When.ToString('yyyy-MM-dd HH:mm') + '|' + $_.Text
  if ($seen.ContainsKey($key)) { $false } else { $seen[$key] = $true; $true }
}
$sorted = @($sorted)

# --- log.html ---------------------------------------------------------------
$rows = New-Object System.Text.StringBuilder
foreach ($e in $sorted) {
  $iso = $e.When.ToString('yyyy-MM-ddTHH:mm', $Culture)
  $shown = $e.When.ToString('yyyy-MM-dd HH:mm', $Culture)
  [void]$rows.AppendLine("      <li><time datetime=""$iso"">$shown</time><span>$(Encode-Html $e.Text)</span></li>")
}
if ($sorted.Count -eq 0) {
  [void]$rows.AppendLine('      <li class="empty"><span>Nothing yet.</span></li>')
}

$page = @'
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
